    def get_subinst_array(self, pattern: str = "") -> List["UniqueModule"]:
        """Return sub-instances whose instance names match ``pattern``.

        Empty pattern matches all. Pattern is a Python regex (``re.search``
        semantics; differs from Perl regex dialect for advanced features).
        Order follows insertion (mirrors Perl ``SubInstanceList`` order;
        UniqueModule.pm:932).
        """
        out: List[UniqueModule] = []
        for name, inst in self._sub_instances.items():
            if not pattern or re.search(pattern, name):
                out.append(inst)
        return out

    def get_instance_obj(
        self, inst: "str | UniqueModule"
    ) -> "UniqueModule":
        """Resolve ``inst`` to a :class:`UniqueModule`.

        - A :class:`UniqueModule` passes through unchanged.
        - A dotted path ``"top.a.b"`` is walked from the top instance.

        Mirrors Perl ``get_instance_obj`` (UniqueModule.pm:1087); the path
        is what ``get_instance_path()`` returns.
        """
        if isinstance(inst, UniqueModule):
            return inst
        if not isinstance(inst, str):
            raise ElaborationError(
                f"{self._module_name}->get_instance_obj: "
                f"expected str or UniqueModule, got {type(inst).__name__}"
            )
        top = self.get_top()
        top_name = top.get_instance_name()
        if not re.fullmatch(rf"{re.escape(top_name)}(\.\w+)*", inst):
            raise ElaborationError(
                f"{self._module_name}->get_instance_obj: "
                f"{inst!r} is not a legal instance path under {top_name!r}"
            )
        stripped = re.sub(rf"^{re.escape(top_name)}\.?", "", inst)
        node: UniqueModule = top
        for tok in (stripped.split(".") if stripped else []):
            if tok not in node._sub_instances:
                raise ElaborationError(
                    f"{self._module_name}->get_instance_obj: "
                    f"cannot find subinst {tok!r} of {inst!r}"
                )
            node = node._sub_instances[tok]
        return node

    def search_subinst(
        self,
        *,
        start_from: "UniqueModule | str | None" = None,
        depth: int = 10000,
        reverse: bool = False,
        path_regex: Optional[str] = None,
        iname_regex: Optional[str] = None,
        mname_regex: Optional[str] = None,
        bname_regex: Optional[str] = None,
        sname_regex: Optional[str] = None,
        has_param_regex: "str | List[str] | None" = None,
        apply_map: Any = None,
    ) -> List["UniqueModule"]:
        """DFS the elaborated hierarchy from ``start_from`` (default: top)
        and filter results by the supplied regex filters and predicate.

        All regex filters AND-compose. An empty-string regex matches
        everything. ``apply_map`` is a callable applied last; instances
        for which it returns falsy are dropped.

        Mirrors Perl ``search_subinst`` (UniqueModule.pm:797). The kwarg
        names are snake_case (Perl wiki uses CamelCase: ``PathRegex``,
        ``INameRegex``, etc.); translate at the call site.
        """
        start = (
            self.get_instance_obj(start_from)
            if start_from is not None
            else self.get_top()
        )

        results: List[UniqueModule] = []

        def _dfs(node: "UniqueModule", d: int) -> None:
            if d >= 0 and not reverse:
                results.append(node)
            if d >= 1:
                for child in node._sub_instances.values():
                    _dfs(child, d - 1)
            if d >= 0 and reverse:
                results.append(node)

        _dfs(start, depth)

        def _match(regex: Optional[str], value: str) -> bool:
            return regex is None or regex == "" or re.search(regex, value) is not None

        def _has_param(node: "UniqueModule", patterns) -> bool:
            params = node.get_mod_param_list()
            pats = patterns if isinstance(patterns, list) else [patterns]
            for p in pats:
                if p == "":
                    continue
                if not any(re.search(p, pname) for pname in params):
                    return False
            return True

        filtered: List[UniqueModule] = []
        for n in results:
            if not _match(path_regex, n.get_instance_path()):
                continue
            if not _match(iname_regex, str(n.iname)):
                continue
            if not _match(mname_regex, str(n.mname)):
                continue
            if not _match(bname_regex, str(n.bname)):
                continue
            if not _match(sname_regex, str(n.sname)):
                continue
            if has_param_regex is not None and not _has_param(n, has_param_regex):
                continue
            if apply_map is not None and not apply_map(n):
                continue
            filtered.append(n)
        return filtered

    # ----------------------------------------------------- product-list DFS
    def get_prod_list_insts(
        self, synth_top: Optional[str]
    ) -> List[Tuple["UniqueModule", bool]]:
        """DFS the elaborated subinstance tree; return ``(inst, is_synth)``
        pairs in Perl ``UniqueModule.pm::_get_prod_list_insts`` order.

        ``synth_top`` is the **dotted** instance path that bounds the
        synth cone (``None`` matches Perl ``SynthTop=undef`` -> every
        instance is verif).  An instance is synth iff its dotted path
        equals ``synth_top`` or starts with ``synth_top + "."``.  The
        traversal yields each ``(outfile_name, is_synth)`` pair at most
        once: this is what lets Manager promote a file seen on both
        sides to ``synth_and_verif``.
        """
        results: List[Tuple[UniqueModule, bool]] = []
        synth_files: set[str] = set()
        verif_files: set[str] = set()
        self._collect_prod_list(results, synth_files, verif_files, "", synth_top)
        return results

    def _collect_prod_list(
        self,
        results: List[Tuple["UniqueModule", bool]],
        synth_files: set,
        verif_files: set,
        path: str,
        synth_top: Optional[str],
    ) -> None:
        if synth_top is not None:
            if self._parent is not None:
                path = f"{path}.{self._instance_name}" if path else self._instance_name
            else:
                path = self._instance_name

        is_synth = synth_top is not None and (
            path == synth_top or path.startswith(synth_top + ".")
        )
        # On the path leading down to synth_top from above (so a verif
        # parent of a synth descendant is still walked into).
        on_synth_path = synth_top is not None and (
            is_synth or synth_top.startswith(path + ".")
        )

        fname = self._outfile_name
        if fname is not None:
            # Skipping the recursion is safe because shared `fname` implies
            # shared `_sub_instances` (clones via `_new_as_clone`).
            if is_synth and fname in synth_files:
                return
            if (not is_synth) and fname in verif_files and not on_synth_path:
                return
            if is_synth:
                synth_files.add(fname)
            else:
                verif_files.add(fname)

        # clone: descend through _clone_of for traversal -- the clone owns
        # no children, but its source's _sub_instances reflects the shared
        # underlying module's elaborated tree.
        descend = self._sub_instances
        if not descend and self._clone_of is not None:
            descend = self._clone_of._sub_instances
        for sub in descend.values():
            sub._collect_prod_list(results, synth_files, verif_files, path, synth_top)

        results.append((self, is_synth))

    def get_parent(self) -> "UniqueModule | None":
        return self._parent

    def get_top(self) -> "UniqueModule":
        node: UniqueModule = self
        while node._parent is not None:
            node = node._parent
        return node

    # ----------------------------------------------------------- diagnostics
    def to_string(self, *args: Any) -> str:
        """Serialise one or more structures to a printable string.

        Mirrors Perl ``to_string`` (UniqueModule.pm:2911). Uses
        :func:`pprint.pformat` per argument; not a byte-for-byte port
        of Perl's ``CfgHandler::PrintToString`` but covers the
        documented "debug-print arbitrary structures" use case.
        """
        if not args:
            raise ParameterError(
                f"{self._module_name}->to_string: "
                f"expected at least one argument"
            )
        return "\n".join(pprint.pformat(a) for a in args)

    def error(self, msg: str) -> None:
        """Raise a fatal error tagged with this module's identity.

        Mirrors Perl ``$self->error(msg)`` / bare ``error(msg)`` in `.vpy`
        bodies (UniqueModule.pm:2803): the user's message is prefixed with
        the current module and instance path so the failure points at the
        source of the elaboration error.
        """
        reporting.error(
            f"{self._module_name}@{self.get_instance_path()}: {msg}",
            fatal=True,
        )

    def warning(self, msg: str) -> None:
        """Emit a non-fatal warning tagged with this module's identity.

        Mirrors Perl ``$self->warning(msg)`` / bare ``warning(msg)``
        (UniqueModule.pm:2863).
        """
        reporting.warning(
            f"{self._module_name}@{self.get_instance_path()}: {msg}"
        )

    # ----------------------------------------------------------- emission
    def emit(self, text: str) -> None:
        if self._outfile_handle is None:
            self._outfile_handle = io.StringIO()
        self._outfile_handle.write(text + "\n")

    def _emit_comment_block(self, lines: List[str]) -> None:
        """Emit ``lines`` as one comment block in ``manager.output_comment`` style.

        A ``str`` style prefixes every line; an ``(open, close)`` tuple emits
        the delimiters on their own whole lines with the payload indented one
        space. Both shapes are required by :func:`_comparable_lines`, which
        strips comments for structural diffing and keys on whole-line
        delimiters.
        """
        style = getattr(self._manager, "output_comment", "//")
        if isinstance(style, tuple):
            open_d, close_d = style
            self.emit(open_d)
            for ln in lines:
                self.emit(f" {ln}")
            self.emit(close_d)
        else:
            for ln in lines:
                self.emit(f"{style} {ln}")

    def emit_param_footer(self) -> None:
        """Append a resolved-parameter provenance block after the module body.

        No-op unless ``manager.param_footer`` is set (``--param-footer``) and
        this module has at least one parameter. Called from the tail of every
        generated ``execute()`` (``template/emitter.CLASS_BODY_TAIL``) after
        the user body and before the final ``_flush_outfile()``, so the block
        lands at the end of the file, past ``endmodule``. Unlike the
        ``to_verilog`` banner -- written before the body runs -- it sees the
        fully resolved parameter set.

        The flag is read off the manager at runtime rather than baked into the
        generated ``.py`` so that a ``--gen-only`` rerun against a stale
        ``raw_dir`` honours the flag it was given, not the one that produced
        the intermediate.

        The rendered lines deliberately separate name from value with ``:``,
        not ``=``: ``tests/_parity_normalize.py`` scans generated files for
        ``// NAME = value`` banner rows, and its window is unbounded on files
        with no ``module`` keyword.
        """
        if not getattr(self._manager, "param_footer", False):
            return
        if not self._params:
            return
        names = sorted(self._params)
        vals = {n: repr(self._params[n]["value"]) for n in names}
        name_w = max(len(n) for n in names)
        # Cap the value column: one long repr (a list or dict parameter) would
        # otherwise pad every other row out to its width. Values past the cap
        # run long rather than being truncated -- a truncated value would lie.
        val_w = min(max(len(v) for v in vals.values()), _PARAM_FOOTER_VALUE_WIDTH)
        lines = ["Genesis-Py resolved parameter provenance"]
        lines += [
            f"  {n:<{name_w}} : {vals[n]:<{val_w}}  <- "
            f"{_param_provenance(self._params[n])}"
            for n in names
        ]
        self._emit_comment_block(lines)

    def to_verilog(self, infile: Optional[str] = None) -> None:
        """Emit a comment banner + parameter table (parity with :2927).

        Style comes from ``manager.output_comment`` via
        :meth:`_emit_comment_block`.
        """
        lines = [
            f"Genesis-Py generated module: {self._unique_module_name}",
            f"Source class: {self._module_name}",
        ]
        if infile is not None:
            lines.append(f"Source file: {infile}")
        if self._params:
            lines.append("Parameters:")
            for k in sorted(self._params):
                lines.append(f"  {k} = {self._params[k]['value']!r}")
        self._emit_comment_block(lines)

    def _execute_child(self, child: "UniqueModule") -> None:
        """Run ``child.execute()`` with the user-config context bound to the
        child, so ``include()`` and other bare-name helpers inside the child's
        body resolve ``self`` to the child (not the parent under elaboration).
        Mirrors the top-level ``with user_config.context(...)`` in
        ``Manager.gen_verilog``.
        """
        from . import user_config

        # The child may not touch its parent's parameters (UniqueModule.pm:833).
        parent_open = self._params_open
        self._params_open = False
        try:
            with user_config.context(self._manager, child):
                child.execute()
        finally:
            self._params_open = parent_open
            child._params_open = False
        child._lock_params()

    def execute(self) -> None:
        """Elaborate this module: open buffer, emit header, flush.

        Generated subclasses (template/emitter._header) call ``super().execute()``
        for the banner + initial flush, then run user body, then re-flush via
        ``_flush_outfile()`` in the footer. The double-flush is intentional:
        plain subclasses (e.g. tests) rely on the base flush; generated bodies
        need to overwrite with body content.
        """
        if self._outfile_handle is None:
            self._outfile_handle = io.StringIO()
        self.to_verilog()
        self._flush_outfile()

    def _flush_outfile(self) -> None:
        """Write current buffer contents to OUTFILE_CONTENT_CACHE under
        ``_unique_module_name`` and every registered synonym name.
        """
        if self._outfile_handle is None:
            return
        suffix = type(self)._OUTPUT_SUFFIX
        self._outfile_name = f"{self._unique_module_name}{suffix}"
        content = self._outfile_handle.getvalue()
        cache.OUTFILE_CONTENT_CACHE[self._outfile_name] = content
        for syn in self._synonyms:
            cache.OUTFILE_CONTENT_CACHE[f"{syn}{suffix}"] = content

